"""Emit experiment results as JSON and a simple standalone HTML page."""

import json
from pathlib import Path

from .metrics import Scores

HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>TranslationBench — document context vs sentence-level</title>
<style>
  body {{ font-family: Georgia, serif; max-width: 720px; margin: 3rem auto; color: #211a1c; }}
  h1 {{ font-size: 1.5rem; }}
  table {{ border-collapse: collapse; width: 100%; margin: 1.5rem 0; }}
  th, td {{ border: 1px solid #e8dedb; padding: .5rem .75rem; text-align: left; }}
  th {{ background: #f6efed; }}
  .delta-pos {{ color: #2e9e5b; font-weight: bold; }}
  .delta-neg {{ color: #d52b1e; font-weight: bold; }}
  footer {{ color: #5c5254; font-size: .85rem; margin-top: 2rem; }}
</style>
</head>
<body>
<h1>Document-level context vs sentence-level translation</h1>
<p>{model} · {n} aligned segments · same source, same reference, same model —
the only variable is whether the model sees the whole document.</p>
<table>
  <tr><th>Metric</th><th>Sentence-level</th><th>Document context</th><th>&Delta;</th></tr>
  {rows}
</table>
<footer>BLEU/chrF via sacreBLEU; COMET via Unbabel wmt22-comet-da.
Generated by TranslationBench (Red Maple Research).</footer>
</body>
</html>
"""


def _row(name: str, base: float | None, ctx: float | None, digits: int = 2) -> str:
    if base is None or ctx is None:
        return f"<tr><td>{name}</td><td>—</td><td>—</td><td>—</td></tr>"
    delta = ctx - base
    cls = "delta-pos" if delta >= 0 else "delta-neg"
    return (
        f"<tr><td>{name}</td><td>{base:.{digits}f}</td><td>{ctx:.{digits}f}</td>"
        f'<td class="{cls}">{delta:+.{digits}f}</td></tr>'
    )


def write_reports(
    out_dir: str | Path,
    model: str,
    n_segments: int,
    sentence: Scores,
    document: Scores,
) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    payload = {
        "model": model,
        "segments": n_segments,
        "sentence_level": sentence.to_dict(),
        "document_context": document.to_dict(),
    }
    json_path = out_dir / "report.json"
    json_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    rows = "\n  ".join(
        [
            _row("BLEU", sentence.bleu, document.bleu),
            _row("chrF", sentence.chrf, document.chrf),
            _row("COMET", sentence.comet, document.comet, digits=4),
        ]
    )
    html_path = out_dir / "report.html"
    html_path.write_text(
        HTML_TEMPLATE.format(model=model, n=n_segments, rows=rows),
        encoding="utf-8",
    )
    return json_path, html_path
